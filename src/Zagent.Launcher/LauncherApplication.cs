using System.Diagnostics;
using System.Runtime.InteropServices;
using System.Security.AccessControl;
using System.Security.Principal;

namespace Zagent.Launcher;

public static class LauncherApplication
{
    public static string FindInstallRoot(string directory)
    {
        for (var current = new DirectoryInfo(directory); current is not null; current = current.Parent)
            if (LaunchPlan.IsInstalledProduct(current.FullName) ||
                LaunchPlan.IsSourceCheckout(current.FullName))
                return current.FullName;
        throw new InvalidOperationException("INSTALL_ROOT_NOT_FOUND");
    }

    /// <summary>
    /// Only starts Core after verified product-bound enrollment and runtime preflight.
    /// activate is used by tests so no live Core must be launched.
    /// </summary>
    public static int Run(string install, string? explicitDataRoot = null,
        Func<ProcessStartInfo, int?>? activate = null)
    {
        if (!OperatingSystem.IsWindows()) throw new PlatformNotSupportedException();
        if (!Environment.UserInteractive) throw new InvalidOperationException("INTERACTIVE_OWNER_REQUIRED");
        using var identity = WindowsIdentity.GetCurrent();
        if (identity.IsSystem || identity.IsAnonymous) throw new InvalidOperationException("INTERACTIVE_OWNER_REQUIRED");
        ValidatePlainPath(install);

        // First click may require ONE local TLS trust approval; never a login.
        // Only a fresh, default-data installation with our packaged helper is
        // eligible. Do not guess or alter another installation's DataRoot.
        if (string.IsNullOrWhiteSpace(explicitDataRoot) &&
            LaunchPlan.IsInstalledProduct(install) &&
            File.Exists(Path.Combine(install, "data", "config", "installed-manifest.json")) &&
            !File.Exists(Path.Combine(install, "data", "config", "dashboard.json")) &&
            File.Exists(Path.Combine(install, "FirstRun-ZagentMultiPlatform.ps1")))
        {
            using var firstRun = Process.Start(BuildFirstRunStartInfo(install))
                ?? throw new InvalidOperationException("FIRST_RUN_START_FAILED");
            firstRun.WaitForExit();
            if (firstRun.ExitCode != 0)
                throw new InvalidOperationException("OWNER_PROVISIONING_INCOMPLETE");
        }

        var data = LaunchPlan.DiscoverDataRoot(install, explicitDataRoot);
        var start = LaunchPlan.Create(install, data);

        ValidatePrivatePath(data, true);
        ValidatePrivatePath(Path.Combine(data, "config"), true);
        // Machine and installed manifests are generated by Core's atomic writer.
        // Their DACL may inherit from the already verified owner-protected config
        // directory. Validate paths, but reserve the strict explicit file ACL
        // contract for the dashboard credentials and DPAPI envelope.
        ValidatePlainPath(Path.Combine(data, "config", "zagent.machine.json"));
        if (LaunchPlan.IsInstalledProduct(install))
            ValidatePlainPath(Path.Combine(data, "config", "installed-manifest.json"));
        ValidatePrivatePath(Path.Combine(data, "config", "dashboard.json"), false);
        ValidatePrivatePath(Path.Combine(data, "config", "internal-secrets.dpapi.json"), false);

        var required = new List<string> { start.FileName,
            Path.Combine(install, "agents", "web", "engine", "dist", "index.js") };
        if (!LaunchPlan.IsInstalledProduct(install))
        {
            required.Add(Path.ChangeExtension(start.FileName, ".dll"));
            required.Add(Path.ChangeExtension(start.FileName, ".runtimeconfig.json"));
            required.Add(Path.ChangeExtension(start.FileName, ".deps.json"));
            required.Add(Path.Combine(start.Environment["DOTNET_ROOT"]!, "dotnet.exe"));
        }
        required.AddRange(new[] { "ZAGENT_FILES_PYTHON", "ZAGENT_TUNNEL_PYTHON",
            "ZAGENT_WEB_NODE", "ZAGENT_ARCMAP_PYTHON" }.Select(key => start.Environment[key]!));
        foreach (var path in required)
        {
            if (!File.Exists(path)) throw new InvalidOperationException("REQUIRED_RUNTIME_MISSING");
            ValidatePlainPath(path);
        }

        var result = (activate ?? Activate)(start);
        if (result is not null and not 0) throw new InvalidOperationException("CORE_START_FAILED");
        return 0;
    }

    public static ProcessStartInfo BuildFirstRunStartInfo(string installRoot)
    {
        var script = Path.Combine(Path.GetFullPath(installRoot), "FirstRun-ZagentMultiPlatform.ps1");
        if (!LaunchPlan.IsInstalledProduct(installRoot) || !File.Exists(script))
            throw new InvalidOperationException("FIRST_RUN_HELPER_MISSING");
        ValidatePlainPath(script);
        var ps = Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.Windows),
            "System32", "WindowsPowerShell", "v1.0", "powershell.exe");
        if (!File.Exists(ps))
            throw new FileNotFoundException("Windows PowerShell is required for first-time HTTPS setup.", ps);
        var start = new ProcessStartInfo(ps)
        {
            WorkingDirectory = Path.GetFullPath(installRoot),
            UseShellExecute = true,
            WindowStyle = ProcessWindowStyle.Normal
        };
        foreach (var argument in new[] { "-NoProfile", "-ExecutionPolicy", "Bypass", "-File", script })
            start.ArgumentList.Add(argument);
        return start;
    }

    // Display a stable diagnostic code without exposing local paths, process
    // arguments, internal credentials, stack traces or exception messages.
    public static string FailureCode(Exception exception)
    {
        if (exception is InvalidOperationException failure &&
            failure.Message is ("INSTALL_ROOT_NOT_FOUND" or "ENROLLMENT_SELECTION_REQUIRED" or
                "ENROLLMENT_INSTALL_MISMATCH" or "REQUIRED_RUNTIME_MISSING" or
                "OWNER_ACL_REQUIRED" or "INTERACTIVE_OWNER_REQUIRED" or
                "REPARSE_PATH_REJECTED" or "CORE_START_FAILED" or
                "FIRST_RUN_START_FAILED" or "FIRST_RUN_HELPER_MISSING" or
                "OWNER_PROVISIONING_INCOMPLETE"))
            return failure.Message;
        return exception switch
        {
            FileNotFoundException => "REQUIRED_FILE_NOT_FOUND",
            UnauthorizedAccessException => "ACCESS_DENIED",
            _ => "STARTUP_UNEXPECTED_ERROR"
        };
    }

    public static int? Activate(ProcessStartInfo start)
    {
        using var process = Process.Start(start) ?? throw new InvalidOperationException("CORE_START_FAILED");
        // Observation is bounded; never kill/restart the child Core.
        return process.WaitForExit(2000) ? process.ExitCode : null;
    }

    private static void ValidatePlainPath(string path)
    {
        for (var current = Path.GetFullPath(path); current is not null; current = Path.GetDirectoryName(current))
            if ((File.GetAttributes(current) & FileAttributes.ReparsePoint) != 0)
                throw new InvalidOperationException("REPARSE_PATH_REJECTED");
    }

    public static void ValidatePrivatePath(string path, bool directory)
    {
        ValidatePlainPath(path);
        using var identity = WindowsIdentity.GetCurrent();
        var owner = identity.User ?? throw new InvalidOperationException("OWNER_SID_UNAVAILABLE");
        FileSystemSecurity acl = directory
            ? new DirectoryInfo(path).GetAccessControl(AccessControlSections.Owner | AccessControlSections.Access)
            : new FileInfo(path).GetAccessControl(AccessControlSections.Owner | AccessControlSections.Access);
        var rules = acl.GetAccessRules(true, true, typeof(SecurityIdentifier)).Cast<FileSystemAccessRule>().ToArray();
        if (!owner.Equals(acl.GetOwner(typeof(SecurityIdentifier))) || !acl.AreAccessRulesProtected || rules.Length != 1 ||
            !owner.Equals(rules[0].IdentityReference) || rules[0].AccessControlType != AccessControlType.Allow ||
            rules[0].IsInherited || rules[0].FileSystemRights != FileSystemRights.FullControl ||
            rules[0].PropagationFlags != PropagationFlags.None ||
            rules[0].InheritanceFlags != (directory ? InheritanceFlags.ContainerInherit | InheritanceFlags.ObjectInherit : InheritanceFlags.None))
            throw new InvalidOperationException("OWNER_ACL_REQUIRED");
    }
}

internal static class Program
{
    [DllImport("user32.dll", CharSet = CharSet.Unicode, EntryPoint = "MessageBoxTimeoutW")]
    private static extern int MessageBoxTimeout(IntPtr owner, string text, string caption, uint type, ushort language, uint milliseconds);

    [STAThread]
    private static int Main()
    {
        try
        {
            return LauncherApplication.Run(
                LauncherApplication.FindInstallRoot(AppContext.BaseDirectory),
                Environment.GetEnvironmentVariable("ZAGENT_LAUNCHER_DATA_ROOT"));
        }
        catch (Exception error)
        {
            var code = LauncherApplication.FailureCode(error);
            MessageBoxTimeout(IntPtr.Zero,
                "Zagent Multi Platform could not open the local Dashboard.\n" +
                "Error code: " + code + "\n" +
                "Only this installation may be configured. No other Zagent installation was modified.\n" +
                "Report this error code for troubleshooting.",
                "Zagent Multi Platform Launcher", 0x10, 0, 15000);
            return 1;
        }
    }
}
